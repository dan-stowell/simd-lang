// shard.go: a home for what no one package owns. In a whole-program build linked in this process, three
// kinds of symbol are needed by many packages and made once: type descriptors (and with them their name
// data, eq/hash closures and method tables), method wrappers and the methods of instantiated types, and
// instances of generic functions. They used to be made by whichever package asked first (a claim in a
// sync.Map), so their unit, and with it their addresses, their neighbours' addresses and the per-unit file
// tables, depended on thread timing: two builds of the same sources gave different binaries.
//
// Here such a symbol belongs to one of nShards shard compilers, chosen by a fixed hash of its name: a
// compiler with an obj.Link of its own and no source files. The asker keeps only a reference by name and
// hands the work to the shard: a descriptor is written right away, by the asking thread, into the shard's
// symbols (descriptors are data and were written by the asking thread before); code (instances, wrappers,
// eq and hash functions) is queued on the shard, and a drain job compiles the shard's queues while
// anything is in them, on a slot of the back end's pool. The work is still done once (the shard's own
// claims), the order in which a shard's items arrive does not matter (NewUnit and installFuncs put a unit
// in one order, canonFiles numbers its files by name), and the shards are the last units the linker gets
// but for the main package, in shard order.
//
// The code a shard generates is compiled as any package outside the runtime's compiles it: the mode of an
// instance (tidy frames, the escape analysis, inferred nosplit) follows the package of its body, as it
// did; the wrappers and eq/hash functions, which took the mode of whichever package asked first, now
// always take the plain one (tools/fc/wbcheck.sh and safecheck.sh check the runtime's nosplit and
// write-barrier rules over the result).
//
// With functions by demand (demand.go) a shard is part of Program.pending: a count from the moment work is
// queued on it until its drain job has emptied its queues, so the program is not quiet while a shard may
// still ask a package for a function.
package main

import (
	"fmt"
	"go/ast"
	"go/token"
	"go/types"
	"log"
	"os"
	"sort"
	"sync"

	"cmd/internal/fclinklib"
	"cmd/internal/obj"
)

const nShards = 64

// shardState is what a shard compiler has besides a compiler's.
type shardState struct {
	idx   int
	mu    sync.Mutex
	busy  bool // a drain job is running (or about to)
	again bool // work was queued while it ran: it looks again
	errs  []string
}

// shardPrio: a drain job's priority for a slot (sched.go): that of a package of about a megabyte.
const shardPrio = int64(1) << 20

// newShards makes the shard compilers of a whole-program build (fc build -link with fclink in process).
func (pr *Program) newShards(sem *prioPool) {
	f := pr.fset.AddFile("<autogenerated>", -1, 1)
	pr.autoPos = token.Pos(f.Base())
	pr.shards = make([]*compiler, nShards)
	for i := range pr.shards {
		path := fmt.Sprintf("go:shard%02d", i)
		p := &Pkg{ImportPath: path, Name: path, info: &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Defs: map[*ast.Ident]types.Object{},
			Uses: map[*ast.Ident]types.Object{}, Instances: map[*ast.Ident]types.Instance{}, Selections: map[*ast.SelectorExpr]*types.Selection{}}}
		c := newCompiler(pr, p, path, "")
		c.fnSem = sem
		c.shard = &shardState{idx: i}
		pr.shards[i] = c
	}
}

// shardOf is the shard of the symbol called name (FNV-1a: the same in every process).
func (pr *Program) shardOf(name string) *compiler {
	h := uint32(2166136261)
	for i := 0; i < len(name); i++ {
		h ^= uint32(name[i])
		h *= 16777619
	}
	return pr.shards[h%nShards]
}

// route: the shard that makes the symbol called name, or nil when c makes it itself (no shards in this
// build, or c is that shard).
func (c *compiler) route(name string) *compiler {
	if c.pr.shards == nil || c.mixed {
		return nil
	}
	if sh := c.pr.shardOf(name); sh != c {
		return sh
	}
	return nil
}

// kick makes sure a drain job will look at the shard's queues (c is a shard; work was just queued on it).
func (c *compiler) kick() {
	sh := c.shard
	if sh == nil {
		return
	}
	sh.mu.Lock()
	if sh.busy {
		sh.again = true
		sh.mu.Unlock()
		return
	}
	sh.busy = true
	sh.mu.Unlock()
	if c.pr.lazyFuncs {
		select {
		case <-c.pr.quiet:
			log.Fatalf("fc: work for %s queued after the back end finished", c.path)
		default:
		}
		c.pr.pending.Add(1)
	}
	c.pr.shardWG.Add(1)
	c.pr.runJob(c.drainShard)
}

// drainShard compiles what is queued on the shard until nothing is.
func (c *compiler) drainShard() {
	sh := c.shard
	try := func(what string, f func()) {
		defer func() {
			if r := recover(); r != nil {
				if b, ok := r.(bail); ok {
					sh.mu.Lock()
					sh.errs = append(sh.errs, what+": "+string(b))
					sh.mu.Unlock()
					return
				}
				fmt.Fprintf(os.Stderr, "fc: internal error in %s (%s)\n", what, c.path)
				panic(r)
			}
		}()
		f()
	}
	c.fnSem.acquire(shardPrio)
	for {
		sh.mu.Lock()
		sh.again = false
		sh.mu.Unlock()
		for {
			c.mu.Lock()
			q := c.instQueue
			c.instQueue = nil
			c.mu.Unlock()
			for _, in := range q {
				try("instance "+in.sym.Name, func() { c.compileInstance(in) })
			}
			did := false
			try("code for type descriptors", func() { did = c.unwrittenTypeCode() })
			if len(q) == 0 && !did {
				break
			}
		}
		sh.mu.Lock()
		if !sh.again {
			sh.busy = false
			sh.mu.Unlock()
			break
		}
		sh.mu.Unlock()
	}
	c.fnSem.release()
	if c.pr.lazyFuncs {
		c.pr.settle(1)
	}
	c.pr.shardWG.Done()
}

// addInstance queues an instance of a generic function on the shard c, once.
func (c *compiler) addInstance(origin *types.Func, env map[*types.TypeParam]types.Type, name string) {
	sym := c.lookup(name, obj.ABIInternal, "_")
	c.mu.Lock()
	if c.instances[name] {
		c.mu.Unlock()
		return
	}
	c.instances[name] = true
	c.instQueue = append(c.instQueue, &instance{fn: origin, env: env, sym: sym})
	c.mu.Unlock()
	c.kick()
}

// addWrapper queues a method wrapper (or the method of an instantiated type) on the shard c, once. r.sym
// is the asker's symbol: the shard defines its own of that name.
func (c *compiler) addWrapper(r wrapperReq) {
	r.sym = c.lookup(r.sym.Name, obj.ABIInternal, r.sym.Pkg)
	c.rtInit()
	c.rtSm.Lock()
	seen := c.rtWrap[r.sym]
	c.rtWrap[r.sym] = true
	if !seen {
		c.needWrapper = append(c.needWrapper, r)
	}
	c.rtSm.Unlock()
	if !seen {
		c.kick()
	}
}

// addAlg queues an equality or hash function (type:.eq.<sig>, type:.hash.<sig>) on the shard c, once.
func (c *compiler) addAlg(name, sig string, t types.Type, hash bool) {
	f := c.lookup(name, obj.ABIInternal, "")
	c.rtInit()
	c.rtSm.Lock()
	seen := c.rtAlg[name]
	c.rtAlg[name] = true
	if !seen {
		if hash {
			c.needHash = append(c.needHash, algReq{sig, f, t})
		} else {
			c.needEq = append(c.needEq, algReq{sig, f, t})
		}
	}
	c.rtSm.Unlock()
	if !seen {
		c.kick()
	}
}

// finishShards waits for the shards' queues to be empty (every package's back end is done: only shards
// can still queue work) and makes their units, in shard order. It returns the errors, by shard.
func (pr *Program) finishShards() ([]*fclinklib.Unit, []string) {
	pr.shardWG.Wait()
	units := make([]*fclinklib.Unit, len(pr.shards))
	var errs []string
	var wg sync.WaitGroup
	for i, c := range pr.shards {
		if len(c.shard.errs) > 0 {
			sort.Strings(c.shard.errs)
			errs = append(errs, c.path+": "+c.shard.errs[0])
			continue
		}
		wg.Add(1)
		go func() {
			defer wg.Done()
			c.installFuncs()
			units[i] = fclinklib.NewUnit(c.ctxt)
		}()
	}
	wg.Wait()
	return units, errs
}
