#!/usr/bin/env python3
"""Regenerate SCOREBOARD.md from the builds run.sh left in $SB_OUT (default /home/exedev/targets/scoreboard).
   mkscoreboard.py > SCOREBOARD.md
Per project and core count: wall clock, critical path and core-seconds, for stock, fair stock and ours.
  go rows:    wall from the timer around `go build`; core-seconds = user+sys of the go command and its children;
              critical path = the longest dependency chain of actions by measured start->done (action graph).
  bazel rows: wall includes starting the Bazel server (fresh output base); core-seconds from the cgroup the client
              and server ran in; critical path as Bazel reports it.
  ours:       $SB_OUT/<name>/ours-p<P>/meta.txt (wall_ms, core_s, crit_ms) when it exists; else "stock fallback".
"""
import os, subprocess, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'trace'))
import mktrace

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.environ.get('SB_OUT', '/home/exedev/targets/scoreboard')
T = '/home/exedev/targets'
CORES = [1, 2, 4, 8]


def corpus():
    for line in open(os.path.join(HERE, 'corpus.txt')):
        if line.startswith('#') or not line.strip(): continue
        name, tool, d, target = line.split(None, 3)
        yield name, tool, d, target.strip()


def cell(d):
    """(wall s, crit s, core s) or None; a failed build is reported as such."""
    p = os.path.join(d, 'meta.txt')
    if not os.path.exists(p): return None
    m = mktrace.meta(p)
    if 'wall_ms' not in m: return None
    if m.get('rc') != '0': return 'FAILED'
    wall = int(m['wall_ms']) / 1000
    if 'core_s' in m: core = float(m['core_s'])
    else: core = float(m['user_s']) + float(m['sys_s'])
    if 'crit_ms' in m: crit = int(m['crit_ms']) / 1000
    elif os.path.exists(os.path.join(d, 'actions.json')): crit = mktrace.Run(d).critical_path()[0]
    else: crit = None
    return wall, crit, core, m


def fmt(c):
    if c is None: return '| | | '
    if c == 'FAILED': return '| failed | | '
    w, cr, co, _ = c
    return f"| {w:.1f} | {'' if cr is None else f'{cr:.1f}'} | {co:.0f} "


def main():
    out = ['# SCOREBOARD', '',
           'Regenerated by `tools/scoreboard/mkscoreboard.py` from the builds `tools/scoreboard/run.sh` ran. Do not edit.',
           '',
           'Every cell is one fresh cold build (CHARTER.md, "What cold means"): empty GOCACHE or a fresh Bazel output',
           'base with the server started inside the timer, page cache dropped, CPUs restricted with `taskset`',
           '(and `-p`/`--jobs`). Seconds; **wall** / **crit** (critical path) / **core-s** (core-seconds).',
           'One run per cell on a noisy shared host: read differences under ~10% as noise.',
           '', '- **stock**: `go build -trimpath`, or `bazel build` with the project\'s own configuration.',
           '- **fair**: stock with the relaxations ours uses: `GOGC=off go build -trimpath -gcflags=all=\'-dwarf=false -l\' -ldflags=\'-s -w\'` (go rows only).',
           '- **ours**: fc (driver/fc), whole program in one process, cold (`tools/scoreboard/ours.sh`): every Go package by fc, the runtime included, linked by fclink (driver/fclink); assembly by the stock assembler; fc\'s heap on a 10 GB pool of explicit huge pages reserved for the run. "stock fallback" where fc does not build the project yet. No critical-path figure yet.', '']
    pins = []
    for name, tool, d, target in corpus():
        out += [f'## {name} ({tool}: `{target}`)', '',
                '| cores | stock wall | crit | core-s | fair wall | crit | core-s | ours wall | crit | core-s |',
                '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
        any_meta = None
        for P in CORES:
            base = os.path.join(OUT, name)
            if tool == 'go':
                s = cell(f'{base}/p{P}-cold'); f = cell(f'{base}/p{P}-cold-fair'); o = cell(f'{base}/ours-p{P}')
            else:
                s = cell(f'{base}/bazel-p{P}'); f = None; o = cell(f'{base}/ours-bazel-p{P}')
            ours = fmt(o) if o else '| stock fallback | | '
            out.append(f'| {P} {fmt(s)}{fmt(f)}{ours}|')
            if isinstance(s, tuple): any_meta = s[3]
        out.append('')
        if any_meta:
            extra = any_meta.get('go') or any_meta.get('bazel') or ''
            procs = any_meta.get('forks') or any_meta.get('processes')
            pins.append(f"| {name} | {tool} | `{d}` | `{any_meta.get('commit', '?')[:12]}` | {extra} | {procs or ''} |")
    out += ['## Pins', '', '| project | tool | directory under /home/exedev/targets | commit | toolchain | processes (8 cores; go: forks, bazel: actions) |',
            '|---|---|---|---|---|---|'] + pins + ['']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
