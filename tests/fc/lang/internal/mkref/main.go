// mkref writes, for each package directory named, the reference copy of the code under test into the
// package's external test package (X.go becomes X_ref_test.go with the package clause changed, so the stock
// compiler compiles the same source the compiler under test does) and auto_test.go, the table of every
// exported non-generic function with its reference (chk.All walks it).
//
//	cd tests/fc/lang && go run ./internal/mkref ints floats ...
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func main() {
	for _, dir := range os.Args[1:] {
		if err := do(dir); err != nil {
			fmt.Fprintln(os.Stderr, "mkref:", err)
			os.Exit(1)
		}
	}
}

func do(dir string) error {
	pkg := filepath.Base(dir)
	old, _ := filepath.Glob(filepath.Join(dir, "*_ref_test.go"))
	for _, f := range old {
		os.Remove(f)
	}
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	clause := regexp.MustCompile(`(?m)^package ` + pkg + `$`)
	var names []string
	fset := token.NewFileSet()
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		src, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		if !clause.Match(src) {
			return fmt.Errorf("%s: no package clause for %s", f, pkg)
		}
		out := clause.ReplaceAll(src, []byte("package "+pkg+"_test"))
		out = append([]byte("// Code generated by internal/mkref from "+filepath.Base(f)+"; DO NOT EDIT.\n\n"), out...)
		if err := os.WriteFile(strings.TrimSuffix(f, ".go")+"_ref_test.go", out, 0o644); err != nil {
			return err
		}
		af, err := parser.ParseFile(fset, f, src, 0)
		if err != nil {
			return err
		}
		for _, d := range af.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv == nil && fd.Name.IsExported() && fd.Type.TypeParams == nil {
				names = append(names, fd.Name.Name)
			}
		}
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/mkref; DO NOT EDIT.\n\npackage %s_test\n\nimport (\n\t\"fclang/internal/chk\"\n\t\"fclang/%s\"\n)\n\nvar autoFuncs = []chk.Fn{\n", pkg, pkg)
	for _, n := range names {
		fmt.Fprintf(&b, "\t{Name: %q, Got: %s.%s, Ref: %s},\n", n, pkg, n, n)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "auto_test.go"), out, 0o644)
}
