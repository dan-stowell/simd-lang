#!/usr/bin/env python3
types = [("I8", "int8"), ("I16", "int16"), ("I32", "int32"), ("I64", "int64"), ("Int", "int"),
         ("U8", "uint8"), ("U16", "uint16"), ("U32", "uint32"), ("U64", "uint64"), ("Uint", "uint"), ("Uptr", "uintptr")]
